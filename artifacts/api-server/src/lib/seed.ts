// Essential accounts that must exist in every environment (dev + production).
// Production is provisioned with only the schema on publish (no data), so these
// accounts are (re)created here on startup. The whole routine is idempotent:
// accounts are matched by email and only inserted when missing, so it is a
// no-op once they exist (e.g. on every subsequent boot and in development).
const DEMO_EMAIL = "anibal.gutierrezbasoalto@gmail.com";
const DEMO_PASSWORD = "Demo2024NextCob!";
const DEMO_RUT = "18027185-6";
const SUPERADMIN_EMAIL = "agutierrez@nextcob.com";

// Demo trial never expires. esDemo already grants permanent access; the
// far-future date keeps every trial/expiry code path happy.
const FAR_FUTURE = new Date("2099-12-31T00:00:00.000Z");

function dateOffset(days: number): string {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
}

async function ensureDemoUser(): Promise<string | null> {
  const [existing] = await db
    .select({ id: usersTable.id, passwordHash: usersTable.passwordHash })
    .from(usersTable)
    .where(eq(usersTable.email, DEMO_EMAIL));
  if (existing) {
    // Self-heal: the demo account must always be able to log in with the known
    // demo password (e2e scripts depend on it). Backfill if the hash is missing.
    if (!existing.passwordHash) {
      await db
        .update(usersTable)
        .set({ passwordHash: await hashPassword(DEMO_PASSWORD) })
        .where(eq(usersTable.id, existing.id));
      logger.info({ email: DEMO_EMAIL }, "Seed: demo account password backfilled");
    }
    return existing.id;
  }

  const passwordHash = await hashPassword(DEMO_PASSWORD);
  const [created] = await db
    .insert(usersTable)
    .values({
      // Reserved public ID: demo is always NCB-0000000003 (see auth.ts /
      // ensureAccountSeqFloor). Explicit override of the GENERATED BY DEFAULT
      // identity; only takes effect on a fresh insert (no-op once it exists).
      accountSeq: 3,
      email: DEMO_EMAIL,
      firstName: "Anibal",
      lastName: "Gutierrezbasoalto",
      rut: DEMO_RUT,
      passwordHash,
      emailVerified: true,
      esDemo: true,
      activo: true,
      subscriptionStatus: "activa",
      trialEndsAt: FAR_FUTURE,
      role: "user",
      profileCompleted: true,
      politicaAceptadaEn: new Date(),
    })
    .onConflictDoNothing()
    .returning({ id: usersTable.id });

  // Keep the anti-abuse ledger consistent (1 RUT = 1 trial).
  await db.insert(trialRutsTable).values({ rut: DEMO_RUT }).onConflictDoNothing();

  if (created) {
    logger.info({ email: DEMO_EMAIL }, "Seed: demo account created");
    return created.id;
  }

  // Lost an insert race: fetch the row the other writer created.
  const [after] = await db
    .select({ id: usersTable.id })
    .from(usersTable)
    .where(eq(usersTable.email, DEMO_EMAIL));
  return after ? after.id : null;
}

// One-time repair for an already-seeded superadmin that has no password yet:
// the nextcob.com domain is not verified in Resend, so the "forgot password"
// email can't reach the superadmin's own inbox. This bcrypt hash corresponds to
// a temporary password shared with the owner out-of-band; it is applied ONLY
// while password_hash is NULL, so it can never overwrite a password the owner
// later sets or changes.
const SUPERADMIN_TEMP_PASSWORD_HASH =
  "$2b$10$3/m3m2qWjwLCycnWYpR2h.f.rQrC0PxaOv5sJGFIuTxPYCdZdLoue";

async function ensureSuperadmin(): Promise<string | null> {
  const [existing] = await db
    .select({ id: usersTable.id, passwordHash: usersTable.passwordHash })
    .from(usersTable)
    .where(eq(usersTable.email, SUPERADMIN_EMAIL));
  if (existing) {
    if (!existing.passwordHash) {
      // Repair: temp password + permanent-access fields, atomic and idempotent.
      await db
        .update(usersTable)
        .set({
          passwordHash: SUPERADMIN_TEMP_PASSWORD_HASH,
          subscriptionStatus: "activa",
          activo: true,
          trialEndsAt: FAR_FUTURE,
          failedLoginAttempts: 0,
          lockedUntil: null,
        })
        .where(and(eq(usersTable.id, existing.id), isNull(usersTable.passwordHash)));
      logger.info(
        { email: SUPERADMIN_EMAIL },
        "Seed: superadmin temp password set (was NULL)",
      );
    }
    return existing.id;
  }

  // No password: the superadmin sets it via the "forgot password" flow (now
  // deliverable because the account exists). role=admin grants permanent access.
  const [created] = await db
    .insert(usersTable)
    .values({
      // Reserved public ID: superadmin is always NCB-0000000001 (see auth.ts /
      // ensureAccountSeqFloor). Explicit override of the GENERATED BY DEFAULT
      // identity; only takes effect on a fresh insert (no-op once it exists).
      accountSeq: 1,
      email: SUPERADMIN_EMAIL,
      firstName: "Soporte",
      lastName: "NextCob",
      passwordHash: SUPERADMIN_TEMP_PASSWORD_HASH,
      emailVerified: true,
      trialEndsAt: FAR_FUTURE,
      esDemo: false,
      activo: true,
      subscriptionStatus: "activa",
      role: "admin",
      profileCompleted: true,
    })
    .onConflictDoNothing()
    .returning({ id: usersTable.id });

  if (created) {
    logger.info({ email: SUPERADMIN_EMAIL }, "Seed: superadmin account created");
    return created.id;
  }

  // Lost an insert race: fetch the row the other writer created.
  const [after] = await db
    .select({ id: usersTable.id })
    .from(usersTable)
    .where(eq(usersTable.email, SUPERADMIN_EMAIL));
  return after ? after.id : null;
}

