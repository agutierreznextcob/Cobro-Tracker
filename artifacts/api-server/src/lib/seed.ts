// El superadmin ya no lleva cobros propios: su módulo de Cobros muestra el
// registro de pagos de suscripción de la plataforma. Limpieza idempotente en
// cada arranque: elimina los cobros/clientes de muestra (y cualquier cobro
// residual) de la cuenta superadmin. Los abonos se borran por cascada.
async function cleanupSuperadminSampleData(superadminUserId: string): Promise<void> {
  const deletedCobros = await db
    .delete(cobrosTable)
    .where(eq(cobrosTable.responsableId, superadminUserId))
    .returning({ id: cobrosTable.id });
  const deletedClientes = await db
    .delete(clientesTable)
    .where(eq(clientesTable.userId, superadminUserId))
    .returning({ id: clientesTable.id });
  if (deletedCobros.length || deletedClientes.length) {
    logger.info(
      { cobros: deletedCobros.length, clientes: deletedClientes.length },
      "Seed: superadmin sample cobros/clientes removed",
    );
  }
}

// Enforce the reserved-ID layout on a fresh database: superadmin =
// NCB-0000000001, NCB-0000000002 is left permanently unassigned, demo =
// NCB-0000000003, and real accounts are handed NCB-0000000004 onward. The two
// reserved accounts are inserted with explicit account_seq values (see
// ensureSuperadmin / ensureDemoUser). Explicit inserts into a GENERATED BY
// DEFAULT identity do NOT advance the underlying sequence, so on a fresh DB the
// next auto-assigned id would collide with a reserved one unless we bump it.
//
// STRICTLY MONOTONIC: we raise the sequence to at least MAX(account_seq)+1 (and
// never below 4), but we also floor it at the sequence's OWN current position so
// it can never be lowered. This matters because accounts can be deleted (ARCO
// "eliminar cuenta"): if the highest-seq account is deleted, MAX drops, and a
// naive setval-to-MAX would hand its account_seq — and thus its permanent NCB
// id — to the next new account. account_id must never be reused. Safe +
// idempotent on every boot.
async function ensureAccountSeqFloor(): Promise<void> {
  await db.execute(sql`
    SELECT setval(
      pg_get_serial_sequence('users', 'account_seq'),
      GREATEST(
        (
          SELECT COALESCE(last_value, 1)
          FROM pg_sequences
          WHERE schemaname || '.' || sequencename
                = pg_get_serial_sequence('users', 'account_seq')
        ),
        (SELECT COALESCE(MAX(account_seq), 0) FROM users),
        3
      ),
      true
    )
  `);
}

// Idempotently ensure the demo + superadmin accounts exist, plus a few sample
// cobros for the demo when it has none. Safe to run on every startup.
export async function seedEssentialAccounts(): Promise<void> {
  const demoUserId = await ensureDemoUser();
  const superadminUserId = await ensureSuperadmin();
  if (demoUserId) {
    await ensureDemoCobros(demoUserId);
  }
  if (superadminUserId) {
    await cleanupSuperadminSampleData(superadminUserId);
  }
  // Must run after the reserved accounts are inserted so the sequence floor
  // accounts for their explicit account_seq values.
  await ensureAccountSeqFloor();
}
